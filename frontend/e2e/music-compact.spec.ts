import { expect, test } from '@playwright/test'
import { musicFixture } from './musicFixture'

test('compact playlist rows keep download details out of the list and expose them on hover or touch', async ({ page }, testInfo) => {
  const app = await musicFixture(page, { playlist: true })
  const error = 'YouTube requires age verification for this recording. Choose another recording.'
  let downloading = false
  const playlist = app.playlists()[0]
  await page.route('**/api/music/playlists/existing', route => route.fulfill({ json: { ...playlist, cache: [{ state: 'cached' }, { state: downloading ? 'downloading' : 'failed', error }] } }))
  await page.goto('/music?tab=playlists&playlist=existing')
  const songs = page.getByLabel('Playlist songs', { exact: true })
  await expect(songs.getByRole('button', { name: 'Downloaded: Dutch song', exact: true })).toBeVisible()
  await expect(page.getByText(error, { exact: true })).toHaveCount(0)
  const failed = songs.getByRole('button', { name: 'Download failed: Another recording', exact: true })
  if (testInfo.project.name === 'touch') await failed.tap()
  else await failed.hover()
  const tooltip = page.getByRole('tooltip')
  await expect(tooltip).toHaveText(error)
  const bounds = await tooltip.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.getByRole('textbox', { name: 'Search this playlist', exact: true }).click()
  await expect(tooltip).toHaveCount(0)
  await failed.focus()
  await expect(tooltip).toHaveText(error)
  await failed.press('Escape')
  await expect(tooltip).toHaveCount(0)
  const heights = await songs.locator('.music-track').evaluateAll(rows => rows.map(row => row.getBoundingClientRect().height))
  for (const height of heights) expect(height).toBeLessThanOrEqual(65)
  await page.getByRole('textbox', { name: 'Search this playlist', exact: true }).fill('Another')
  await expect(songs.locator('.music-track')).toHaveCount(1)
  await songs.getByRole('button', { name: 'Download failed: Another recording', exact: true }).focus()
  await expect(tooltip).toHaveText(error)
  await page.screenshot({ path: testInfo.outputPath('compact-song-download-details.png') })
  downloading = true
  await page.reload()
  const progress = songs.getByRole('button', { name: 'Downloading: Another recording', exact: true })
  await expect(progress).toBeVisible()
  await expect(page.getByText('Downloading this recording in the background.', { exact: true })).toHaveCount(0)
  await progress.focus()
  await expect(tooltip).toHaveText('Downloading this recording in the background.')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
})

test('read-only playlist rows retain saving without exposing edit or remove', async ({ page }) => {
  const app = await musicFixture(page, { playlist: true, outside: true })
  const playlist = app.playlists()[0]
  await page.route('**/api/state', async route => { const response = await route.fetch(); const base = await response.json(); await route.fulfill({ json: { ...base, user: { ...base.user, admin: false }, status: { ...base.status, audio_mode: 'music' } } }) })
  await page.route('**/api/music/playlists/existing', route => route.fulfill({ json: { ...playlist, creator_id: 'someone-else' } }))
  await page.goto('/music?tab=playlists&playlist=existing')
  const songs = page.getByLabel('Playlist songs', { exact: true })
  await expect(songs.locator('.music-save')).toHaveCount(2)
  const trigger = songs.getByRole('button', { name: 'More options for Dutch song', exact: true })
  await trigger.click()
  await expect(page.getByRole('menuitem', { name: 'Edit', exact: true })).toHaveCount(0)
  await expect(page.getByRole('menuitem', { name: 'Remove from playlist', exact: true })).toHaveCount(0)
  await page.getByRole('menuitem', { name: 'Add to playlist', exact: true }).click()
  const menu = page.getByRole('dialog', { name: 'Save Dutch song', exact: true })
  await menu.getByRole('checkbox', { name: /Liked Songs/ }).click()
  await expect(menu.getByRole('checkbox', { name: /Liked Songs/ })).toHaveAttribute('aria-checked', 'true')
  await menu.press('Escape')
  await expect(trigger).toBeFocused()
  expect(app.likes()).toHaveLength(1)
})


test('playlist save check appears beside duration on hover and stays usable while its menu is open', async ({ page }, testInfo) => {
  await musicFixture(page, { playlist: true })
  await page.goto('/music?tab=playlists&playlist=existing')
  const songs = page.getByLabel('Playlist songs', { exact: true })
  const save = songs.getByRole('button', { name: 'Save Dutch song to playlists', exact: true })
  const container = save.locator('..')
  if (testInfo.project.name === 'desktop') {
    await expect(container).toHaveCSS('opacity', '0')
    await songs.locator('article').first().hover()
  }
  await expect(container).toHaveCSS('opacity', '1')
  await expect(save).toHaveAttribute('data-saved', 'true')
  const button = await save.boundingBox()
  const duration = await songs.locator('.music-track-duration').first().boundingBox()
  expect(button!.x + button!.width).toBeLessThanOrEqual(duration!.x)
  await save.click()
  const menu = page.getByRole('dialog', { name: 'Save Dutch song', exact: true })
  await expect(menu.getByRole('checkbox', { name: /Favourites/ })).toHaveAttribute('aria-checked', 'true')
  await menu.getByRole('checkbox', { name: /Liked Songs/ }).click()
  await expect(menu.getByRole('checkbox', { name: /Liked Songs/ })).toHaveAttribute('aria-checked', 'true')
  await expect(container).toHaveCSS('opacity', '1')
  await menu.press('Escape')
  await expect(save).toBeFocused()
  await expect(songs.locator('article').first()).toBeVisible()
})
