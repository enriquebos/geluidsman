import { expect, test } from '@playwright/test'

test('caption language supports keyboard navigation after opening the options', async ({ page }) => {
  await page.goto('/videos')
  const field = page.getByRole('button', { name: 'Caption language', exact: true })
  await field.focus()
  await field.press('ArrowDown')
  const all = page.getByRole('option', { name: 'Dutch + English', exact: true })
  const dutch = page.getByRole('option', { name: 'Dutch', exact: true })
  const english = page.getByRole('option', { name: 'English', exact: true })
  await expect(all).toBeFocused()
  await all.press('ArrowDown')
  await expect(dutch).toBeFocused()
  await dutch.press('End')
  await expect(english).toBeFocused()
  await english.press('Home')
  await expect(all).toBeFocused()
  await all.press('ArrowDown')
  await dutch.press('Enter')
  await expect(field).toHaveText('Dutch')
  await expect(page.getByRole('listbox', { name: 'Caption language options' })).toHaveCount(0)
  await field.focus()
  await field.press('ArrowUp')
  await expect(english).toBeFocused()
  await english.press('ArrowUp')
  await expect(dutch).toBeFocused()
  await dutch.press('Escape')
  await expect(field).toBeFocused()
  await expect(field).toHaveAttribute('aria-expanded', 'false')
})
