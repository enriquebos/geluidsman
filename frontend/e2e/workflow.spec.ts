test('video preview, precision trim, clip persistence, edit and delete', async ({ page, request }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Video library' }).click()
  await page.getByRole('button', { name: 'Watch & cut' }).first().click()
  await expect(page.getByRole('heading', { name: 'Cut a new sound' })).toBeVisible()
  await expect(page.getByRole('slider', { name: 'Clip volume' })).toHaveCount(0)
  const start = page.getByTestId('trim-start')
  await expect(start).toBeVisible()
  await expect(page.getByRole('button', { name: 'Preview cut' })).toBeEnabled()
  await page.getByTestId('wave-viewport').evaluate(element => element.scrollIntoView({ block: 'center' }))

  const before = await page.getByLabel('Start time').inputValue()
  if (testInfo.project.name === 'touch') {
    const point = await start.boundingBox()
    const session = await page.context().newCDPSession(page)
    const x = point!.x + point!.width / 2 + 3
    const y = point!.y + point!.height / 2
    await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
    await expect(page.getByText('Precision mode · 4×')).toBeVisible()
    await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + 45, y }] })
    await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await session.detach()
  } else {
    const point = await start.boundingBox()
    await page.mouse.move(point!.x + point!.width / 2 + 2, point!.y + point!.height / 2)
    await page.mouse.down()
    await expect(page.getByText('Precision mode · 4×')).toBeVisible()
    await page.mouse.move(point!.x + point!.width / 2 + 47, point!.y + point!.height / 2)
    await page.mouse.up()
  }
  await expect(page.getByText('Precision mode · 4×')).not.toBeVisible()
  expect(Number(await page.getByLabel('Start time').inputValue())).toBeGreaterThan(Number(before))
  await page.getByLabel('Start time').fill('1')
  await page.getByLabel('End time').fill('2.5')
  await page.getByRole('button', { name: 'Preview cut' }).click()
  await expect(page.locator('video')).toHaveJSProperty('paused', true, { timeout: 10000 })
  const name = `Browser test ${testInfo.project.name} ${Date.now()}`
  await page.getByLabel('Sound name', { exact: true }).fill(name)
  await page.getByLabel('Emoji', { exact: true }).fill('🔊')
  await page.getByRole('button', { name: 'Add to soundboard' }).click()
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: `Play ${name} in Discord`, exact: true })).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  const card = page.locator('.sound-card').filter({ has: page.getByRole('heading', { name, exact: true }) })
  await card.getByRole('button', { name: 'Preview', exact: true }).click()
  await expect(card.getByRole('button', { name: 'Stop preview', exact: true })).toBeVisible()
  await expect(card.getByRole('button', { name: 'Stop preview', exact: true }).locator('svg.lucide-headphones')).toBeVisible()
  await page.getByRole('button', { name: `Edit ${name}`, exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('slider', { name: 'Volume', exact: true })).toHaveValue('1')
  await page.getByRole('dialog').getByLabel('Sound name').fill(`${name} edited`)
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByRole('heading', { name: `${name} edited`, exact: true })).toBeVisible()
  await page.getByRole('button', { name: `Edit ${name} edited`, exact: true }).click()
  await page.getByRole('button', { name: 'Delete sound' }).click()
  await expect(page.getByRole('dialog')).toContainText('permanently removes the sound from the soundboard')
  await expect(page.getByRole('dialog')).toContainText('cannot be undone')
  await page.getByRole('dialog').getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.getByRole('heading', { name: `${name} edited`, exact: true })).toHaveCount(0)
  expect(errors).toEqual([])
  const response = await request.get('/api/state')
  expect(JSON.stringify(await response.json())).not.toContain('MTUw')
})

