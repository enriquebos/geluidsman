test('successful channel notices clear on reload while unfinished and failed batches remain', async ({ page }) => {
  let completed = false
  await page.route('**/api/state*', async route => {
    const response = await route.fetch()
    const state = await response.json()
    const batch = { url: 'https://www.youtube.com/@KudNL/videos', error: null, total: 5, current: null }
    state.channel_imports = [
      { ...batch, id: 'old', title: 'Previous import', status: 'complete', counts: { complete: 5 } },
      { ...batch, id: 'skipped', title: 'Already saved import', status: 'complete', counts: { skipped: 5 } },
      { ...batch, id: 'current', title: 'Current import', status: completed ? 'complete' : 'running', counts: completed ? { complete: 5 } : { queued: 5 } },
      { ...batch, id: 'paused', title: 'Paused import', status: 'paused', counts: { queued: 5 } },
      { ...batch, id: 'failed', title: 'Failed import', status: 'complete', counts: { complete: 4, failed: 1 } },
      { ...batch, id: 'error', title: 'Import with error', status: 'failed', error: 'Channel unavailable', counts: {} },
    ]
    await route.fulfill({ response, json: state })
  })
  await page.route('**/api/channel-imports/current/pause', async route => {
    completed = true
    await route.fulfill({ json: { ok: true } })
  })
  await page.goto('/videos')
  const notices = page.getByRole('region', { name: 'Channel imports' })
  await expect(notices.getByText('Previous import', { exact: true })).toHaveCount(0)
  await expect(notices.getByText('Already saved import', { exact: true })).toHaveCount(0)
  await notices.getByRole('button', { name: 'Pause channel' }).click()
  await expect(notices.getByText('complete · 5 imported · 0 already saved · 0 failed · 0 queued')).toBeVisible()
  await page.getByRole('button', { name: 'Soundboard', exact: false }).click()
  await page.getByRole('button', { name: 'Video library', exact: false }).click()
  await expect(notices.getByText('Current import', { exact: true })).toBeVisible()
  await page.reload()
  await expect(notices.getByText('Paused import', { exact: true })).toBeVisible()
  await expect(notices.getByText('Failed import', { exact: true })).toBeVisible()
  await expect(notices.getByText('Channel unavailable', { exact: true })).toBeVisible()
  await expect(notices.getByText('Current import', { exact: true })).toHaveCount(0)
  await expect(notices.getByText('Previous import', { exact: true })).toHaveCount(0)
})

