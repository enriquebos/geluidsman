import { expect, test } from '@playwright/test'
import { musicFixture } from './musicFixture'
import { selectOption } from './select-option'

test('Settings uses vertical Admin navigation and bounded personal controls without moving outer bars', async ({ page }, testInfo) => {
  await musicFixture(page, { mode: 'soundboard' })
  await page.goto('/settings')
  const navigation = page.getByRole('navigation', { name: 'Settings navigation', exact: true })
  await expect(navigation.getByRole('button', { name: 'Personal settings', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(navigation.getByRole('button', { name: 'Admin', exact: true })).toHaveAttribute('aria-expanded', 'true')
  await expect(navigation.getByRole('button')).toHaveCount(10)
  const volume = page.getByRole('slider', { name: 'Browser preview volume', exact: true })
  await expect(volume).toBeVisible()
  expect((await volume.boundingBox())!.width).toBeLessThanOrEqual(340)
  await expect(page.getByRole('button', { name: 'Preferred caption language', exact: true })).toBeVisible()
  const frame = () => page.locator('.sidebar,.connection-bar,.playback-bar').evaluateAll(elements => elements.map(element => { const { x, y, width, height } = element.getBoundingClientRect(); return { x, y, width, height } }))
  await page.evaluate(() => document.fonts.ready)
  const before = await frame()
  await navigation.getByRole('button', { name: 'General', exact: true }).click()
  await expect(page).toHaveURL('/admin?tab=settings')
  await expect(page.getByRole('heading', { name: 'Application settings', exact: true })).toBeVisible()
  await expect(page.getByRole('log', { name: 'Application logs' })).toHaveCount(0)
  await navigation.getByRole('button', { name: 'Conversation', exact: true }).click()
  await expect(page).toHaveURL('/admin?tab=conversation')
  await page.goBack()
  await expect(navigation.getByRole('button', { name: 'General', exact: true })).toHaveAttribute('aria-current', 'page')
  expect(await frame()).toEqual(before)
  await navigation.getByRole('button', { name: 'Personal settings', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('settings-workspace.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
})

test('Application console retains pause, filter and reading position across Admin and personal pages', async ({ page }) => {
  await musicFixture(page, { mode: 'soundboard' })
  const entries = Array.from({ length: 100 }, (_, index) => ({ id: index + 1, timestamp: 1700000000, level: 'INFO', source: 'app.test', message: `Console line ${index + 1}` }))
  await page.route('**/api/admin/logs?*', route => route.fulfill({ json: { entries: new URL(route.request().url()).searchParams.get('after') === '0' ? entries : [], cursor: 100, truncated: false } }))
  await page.goto('/admin?tab=console')
  const navigation = page.getByRole('navigation', { name: 'Settings navigation', exact: true })
  const logs = page.getByRole('log', { name: 'Application logs' })
  await expect(logs).toContainText('Console line 100')
  await page.getByRole('checkbox', { name: 'Follow latest', exact: true }).uncheck()
  await selectOption(page.getByLabel('Log level'), 'INFO')
  await page.getByRole('button', { name: 'Pause logs', exact: true }).click()
  await logs.evaluate(element => { element.scrollTop = 40 })
  await navigation.getByRole('button', { name: 'Permissions', exact: true }).click()
  await expect(logs).toBeHidden()
  await navigation.getByRole('button', { name: 'Personal settings', exact: true }).click()
  await navigation.getByRole('button', { name: 'Application console', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Resume logs', exact: true })).toBeVisible()
  await expect(page.getByRole('checkbox', { name: 'Follow latest', exact: true })).not.toBeChecked()
  await expect(page.getByLabel('Log level')).toContainText('INFO')
  await expect.poll(() => logs.evaluate(element => element.scrollTop)).toBe(40)
})

test('Admin navigation collapses and keyboard navigation stays within the Admin group', async ({ page }) => {
  await musicFixture(page, { mode: 'soundboard' })
  await page.goto('/settings')
  const navigation = page.getByRole('navigation', { name: 'Settings navigation', exact: true })
  const admin = navigation.getByRole('button', { name: 'Admin', exact: true })
  await admin.click()
  await expect(navigation.getByRole('button', { name: 'General', exact: true })).toBeHidden()
  await page.reload()
  await expect(admin).toHaveAttribute('aria-expanded', 'false')
  await admin.click()
  const permissions = navigation.getByRole('button', { name: 'Permissions', exact: true })
  await permissions.focus()
  await permissions.press('Home')
  await expect(navigation.getByRole('button', { name: 'General', exact: true })).toBeFocused()
  await page.keyboard.press('End')
  await expect(navigation.getByRole('button', { name: 'Application console', exact: true })).toBeFocused()
})
