test('leaving a pending search restores the search controls and ignores its late result', async ({ page }) => {
  await musicFixture(page, { playlist: true })
  let reply: (() => Promise<void>) | null = null
  await page.route('**/api/music/search?*', async route => {
    if (new URL(route.request().url()).searchParams.get('q') !== 'slow search') { await route.fallback(); return }
    reply = () => route.fulfill({ json: { tracks: [] } })
  })
  await page.goto('/music')
  await page.getByRole('textbox', { name: 'Search music', exact: true }).fill('slow search')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.getByText('Finding songs…', { exact: true })).toBeVisible()
  const library = page.getByRole('complementary', { name: 'Playlist library', exact: true })
  if (!(await library.isVisible())) await page.getByRole('button', { name: 'Playlist library', exact: true }).click()
  await library.getByRole('button', { name: /Favourites Your playlist/ }).click()
  await expect(page.getByRole('heading', { name: 'Favourites', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Search', exact: true })).toBeEnabled()
  await (reply as unknown as () => Promise<void>)()
  await expect(page.getByRole('heading', { name: 'Favourites', exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'Search music', exact: true }).fill('Dutch song')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Search results', exact: true })).toBeVisible()
  await expect(page.getByLabel('Search results', { exact: true }).locator('.music-track')).toHaveCount(2)
})
