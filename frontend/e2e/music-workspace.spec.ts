test('whole playlist row drags like queue and song controls retain their actions', async ({ page }, testInfo) => {
  const app = await musicFixture(page, { playlist: true })
  await page.goto('/music?tab=playlists&playlist=existing')
  const songs = page.getByLabel('Playlist songs', { exact: true })
  const source = songs.getByRole('article', { name: 'Reorder Dutch song', exact: true })
  const target = songs.getByRole('article', { name: 'Reorder Another recording', exact: true })
  await expect(source.locator('.music-drag-handle')).toHaveCount(0)
  await source.evaluate(element => element.scrollIntoView({ block: 'center' }))
  const from = await source.boundingBox()
  const to = await target.boundingBox()
  const x = from!.x + from!.width - 50
  const y = from!.y + 14
  if (testInfo.project.name === 'touch') {
    const client = await page.context().newCDPSession(page)
    await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
    await expect(page.locator('.music-sort-ghost')).toHaveCount(1)
    await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: to!.y + to!.height - 8 }] })
    await expect(target).toHaveCSS('transform', /matrix/)
    await page.screenshot({ path: testInfo.outputPath('playlist-whole-row-drag.png') })
    await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await client.detach()
  } else {
    await page.mouse.move(x, y)
    await page.mouse.down()
    await page.mouse.move(x, y + 12, { steps: 2 })
    await expect(page.locator('.music-sort-ghost')).toHaveCount(1)
    await page.mouse.move(x, to!.y + to!.height - 8, { steps: 8 })
    await expect(target).toHaveCSS('transform', /matrix/)
    await page.screenshot({ path: testInfo.outputPath('playlist-whole-row-drag.png') })
    await page.mouse.up()
  }
  await expect.poll(() => app.playlists()[0].tracks.map(track => track.title)).toEqual(['Another recording', 'Dutch song'])
  await expect(page.locator('.music-sort-ghost')).toHaveCount(0)
  await songs.getByRole('button', { name: 'More options for Dutch song', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: 'Edit', exact: true })).toBeVisible()
  await page.getByRole('menu', { name: 'Options for Dutch song' }).press('Escape')
  await songs.getByRole('button', { name: 'Play Dutch song now', exact: true }).click()
  expect(app.immediatePlays()).toBe(1)
  expect(app.playlists()[0].tracks.map(track => track.title)).toEqual(['Another recording', 'Dutch song'])
})

