test('vocabulary hints save, persist and clear while the model is loading', async ({ page }) => {
  let hints = ''
  await page.route('**/api/admin/transcription', route => route.fulfill({ json: { ready: false, model: 'large-v3-turbo', phase: 'loading' } }))
  await page.route('**/api/admin/transcription/vocabulary', async route => {
    if (route.request().method() === 'PUT') hints = route.request().postDataJSON().hints.trim()
    await route.fulfill({ json: { hints } })
  })
  await page.goto('/admin?tab=conversation')
  const input = page.getByRole('textbox', { name: 'Vocabulary hint 1', exact: true })
  const save = page.getByRole('button', { name: 'Save vocabulary hints', exact: true })
  await expect(input).toBeEnabled()
  await expect(input).toHaveValue('')
  await expect(save).toBeDisabled()
  await input.fill('Zoë')
  await page.getByRole('button', { name: 'Add vocabulary hint', exact: true }).click()
  await page.getByRole('textbox', { name: 'Vocabulary hint 2', exact: true }).fill('Brr Brr Patapim')
  await expect(page.locator('.transcription-vocabulary')).toContainText('Unsaved changes')
  const box = await input.boundingBox()
  expect(box!.x + box!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  await save.click()
  await expect(save).toBeDisabled()
  await expect(page.locator('.transcription-vocabulary')).toContainText('Saved hints apply')
  await page.reload()
  await expect(input).toHaveValue('Zoë')
  await expect(page.getByRole('textbox', { name: 'Vocabulary hint 2', exact: true })).toHaveValue('Brr Brr Patapim')
  await page.getByRole('button', { name: 'Clear hints', exact: true }).click()
  await expect(save).toBeEnabled()
  await save.click()
  await page.reload()
  await expect(input).toHaveValue('')
  await expect(page.locator('.transcription-vocabulary')).toContainText('No vocabulary hints configured')
})

test('failed vocabulary saves preserve the draft and allow retry', async ({ page }) => {
  let fail = true
  await page.route('**/api/admin/transcription/vocabulary', async route => {
    if (route.request().method() === 'PUT' && fail) await route.fulfill({ status: 503, json: { detail: 'Try again' } })
    else await route.fulfill({ json: { hints: route.request().method() === 'PUT' ? route.request().postDataJSON().hints : '' } })
  })
  await page.goto('/admin?tab=conversation')
  const input = page.getByRole('textbox', { name: 'Vocabulary hint 1', exact: true })
  const save = page.getByRole('button', { name: 'Save vocabulary hints', exact: true })
  await expect(input).toBeEnabled()
  await input.fill('Sjoerd')
  await save.click()
  await expect(input).toHaveValue('Sjoerd')
  await expect(save).toBeEnabled()
  await expect(page.locator('.transcription-vocabulary')).toContainText('Unsaved changes')
  fail = false
  await save.click()
  await expect(save).toBeDisabled()
})

test('admin switches between API and local providers', async ({ page }) => {
  let provider = 'local'
  const status = () => ({ provider, ready: true, model: provider === 'local' ? 'large-v3-turbo' : 'nova-3', device: provider === 'local' ? 'mlx' : 'deepgram', models: provider === 'local' ? ['large-v3-turbo', 'large-v3'] : ['nova-3'], phase: 'ready' })
  await page.route('**/api/admin/transcription', route => route.fulfill({ json: status() }))
  await page.route('**/api/admin/transcription/provider', route => { provider = route.request().postDataJSON().provider; return route.fulfill({ json: status() }) })
  await page.goto('/admin?tab=conversation')
  const selector = page.getByRole('button', { name: 'Transcription provider', exact: true })
  await expect(selector).toContainText('Local')
  await selector.click()
  await page.getByRole('option', { name: 'API · Deepgram Nova-3', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Transcription model', exact: true })).toContainText('Nova-3')
  await expect(page.locator('.transcription-settings')).toContainText('Audio is sent to Deepgram')
  await page.reload()
  await expect(selector).toContainText('API')
  await selector.click()
  await page.getByRole('option', { name: /Local/ }).click()
  await expect(page.getByRole('button', { name: 'Transcription model', exact: true })).toContainText('large-v3-turbo')
})

