test('conversation controls group vocabulary with keyterms and persist language choices', async ({ page }) => {
  let language = 'nl'
  await page.route('**/api/admin/transcription', route => route.fulfill({ json: { provider: 'deepgram', device: 'deepgram', model: 'nova-3', ready: true, phase: 'configured', models: ['nova-3'], language } }))
  await page.route('**/api/admin/transcription/language', route => { language = route.request().postDataJSON().language; return route.fulfill({ json: { language } }) })
  await page.goto('/admin?tab=conversation')
  const dropdown = page.getByRole('button', { name: 'Transcription language', exact: true })
  await expect(dropdown).toContainText('Dutch (nl)')
  await dropdown.click()
  await page.getByRole('option', { name: 'Multilingual (multi)', exact: true }).click()
  await expect(dropdown).toContainText('Multilingual (multi)')
  await page.reload()
  await expect(dropdown).toContainText('Multilingual (multi)')
  await dropdown.click()
  await page.getByRole('option', { name: 'English (en)', exact: true }).click()
  await expect(dropdown).toContainText('English (en)')
  const keyterms = page.locator('.deepgram-option').filter({ has: page.getByRole('switch', { name: 'Keyterm Prompting', exact: true }) })
  await expect(keyterms.getByRole('textbox', { name: 'Vocabulary hint 1', exact: true })).toBeVisible()
  await expect(keyterms).not.toContainText('/500 characters')
  await expect(page.getByRole('switch', { name: 'Keywords', exact: true })).toHaveCount(0)
  const provider = await page.getByRole('button', { name: 'Transcription provider', exact: true }).boundingBox()
  const model = await page.getByRole('button', { name: 'Transcription model', exact: true }).boundingBox()
  expect(model!.y - (provider!.y + provider!.height)).toBeGreaterThanOrEqual(24)
})
